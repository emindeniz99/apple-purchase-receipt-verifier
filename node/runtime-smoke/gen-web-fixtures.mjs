// Writes the fixture bytes the isolate runners embed, as a module with no
// imports. Fastly Compute has no filesystem and its build step is a
// bundler, so a fixture has to arrive as source. Regenerated on every run
// so the embedded bytes cannot drift from the files on disk.
//   node runtime-smoke/gen-web-fixtures.mjs <output.js>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (rel) => fileURLToPath(new URL(rel, import.meta.url));
const bytes = (rel) => readFileSync(here(rel));
const text = (rel) => readFileSync(here(rel), 'ascii');

const BINARY = {
  appleRootDer: '../certs/AppleIncRootCertificate.cer',
  jwsRootDer: '../../fixtures/generated/jws-root.der',
  foreignReceiptDer: '../../fixtures/generated/receipt-foreign.der',
};
const TEXT = {
  sandboxReceiptB64: '../../fixtures/public-receipts/receipt-sandbox-g5.b64',
  legacyReceiptB64: '../../fixtures/public-receipts/receipt-sandbox-legacy.b64',
  transactionJws: '../../fixtures/generated/transaction.jws',
};

const parts = ['// GENERATED by runtime-smoke/gen-web-fixtures.mjs — do not edit or commit.\n'];
parts.push('const hex = (s) => {\n'
  + '  const out = new Uint8Array(s.length / 2);\n'
  + '  for (let i = 0; i < out.length; i += 1) out[i] = parseInt(s.substr(i * 2, 2), 16);\n'
  + '  return out;\n};\n');
for (const [name, rel] of Object.entries(BINARY)) {
  parts.push(`export const ${name} = hex(${JSON.stringify(bytes(rel).toString('hex'))});\n`);
}
for (const [name, rel] of Object.entries(TEXT)) {
  parts.push(`export const ${name} = ${JSON.stringify(text(rel))};\n`);
}

const [out] = process.argv.slice(2);
if (!out) {
  console.error('usage: gen-web-fixtures.mjs <output.js>');
  process.exit(2);
}
writeFileSync(out, parts.join('\n'));
